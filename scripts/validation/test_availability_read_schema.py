"""Public-read shape fixtures only; no HTTP or availability-guard runtime proof."""
import copy
import json
from pathlib import Path
import unittest

from jsonschema import Draft202012Validator, FormatChecker

SCHEMA = Path(__file__).resolve().parents[2] / "docs/phase-1-architecture/contracts/availability-read.schema.json"


def synthetic_offer():
    return {"department_id": "ROUTE-WING-STRATEGY", "availability": {"state": "available", "expires_at": "2041-02-03T04:05:06.125Z"}}


class AvailabilityReadShapeTests(unittest.TestCase):
    def setUp(self):
        schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
        Draft202012Validator.check_schema(schema)
        checker = FormatChecker(formats=["date-time"])
        self.assertIn("date-time", checker.checkers, "Required format checker must not be silently absent")
        self.assertFalse(checker.conforms("2041-02-31T04:05:06Z", "date-time"))
        self.validator = Draft202012Validator(schema, format_checker=checker)

    def test_state_expiry_and_private_projection(self):
        # FR-009/AF-02 require truthful minimal presence; this only checks proposed wire shape.
        offer = synthetic_offer()
        self.assertEqual(list(self.validator.iter_errors(offer)), [])
        unavailable = {"department_id": "ROUTE-WING-STRATEGY", "availability": {"state": "unavailable"}}
        self.assertEqual(list(self.validator.iter_errors(unavailable)), [])
        for instant in ("2041-02-31T04:05:06Z", "2041-02-03T04:05:06+00:00", "2041-02-03T04:05:06Z\n", "2041-02"):
            with self.subTest(instant=instant):
                changed = copy.deepcopy(offer)
                changed["availability"]["expires_at"] = instant
                self.assertTrue(list(self.validator.iter_errors(changed)))
        invalid = [
            {"department_id": "ROUTE-WING-STRATEGY", "availability": {"state": "available"}},
            {"department_id": "ROUTE-WING-STRATEGY", "availability": {"state": "unknown"}},
            {"department_id": "ROUTE-WING-STRATEGY", "availability": {"state": "unavailable", "expires_at": "2041-02-03T04:05:06Z"}},
            {"department_id": "synthetic_private_department", "availability": {"state": "unavailable"}},
            dict(offer, staff_id="synthetic_private_staff"),
        ]
        for private_key in ("setting_id", "revision", "teams_state", "queue_count", "calendar", "reason"):
            changed = copy.deepcopy(offer)
            changed["availability"][private_key] = "synthetic_private_value"
            invalid.append(changed)
        for instance in invalid:
            with self.subTest(instance=instance):
                self.assertTrue(list(self.validator.iter_errors(instance)))

    def test_closed_correlated_error_body(self):
        # Fixed proposal oracles; no values generated by enumerating the schema.
        error = {"error": {"code": "AVAILABILITY_READ_UNAVAILABLE", "explanation": "Public availability information is temporarily unavailable.", "retryability": "retry_read"}}
        self.assertEqual(list(self.validator.iter_errors(error)), [])
        changed = copy.deepcopy(error)
        changed["error"]["retryability"] = "refresh_context"
        missing = copy.deepcopy(error)
        del missing["error"]["explanation"]
        diagnostic = copy.deepcopy(error)
        diagnostic["error"]["staff_id"] = "synthetic_private_staff"
        for instance in (changed, missing, diagnostic, dict(error, **synthetic_offer())):
            with self.subTest(instance=instance):
                self.assertTrue(list(self.validator.iter_errors(instance)))


if __name__ == "__main__":
    unittest.main()
